  /* gated, unnormalised shapes. Ejection = -dV/dphi of the Wiggers volume while a semilunar valve is open; filling = +dV/dphi while an AV valve is open. */
  function rawEject(p,tm,w){return Math.max(0,dSqueeze(p,tm))*semilunar(p,w)}
  function rawFill(p,tm,w){return Math.max(0,-dSqueeze(p,tm))*atrioventricular(p,w)}
