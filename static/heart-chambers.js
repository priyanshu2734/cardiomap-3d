    const w=new Float32Array(N),q=new Float32Array(N),rho=new Float32Array(N),th=new Float32Array(N),jit=new Float32Array(N),side=new Uint8Array(N),variant=new Uint8Array(N),
      pos=new Float32Array(N*3),seg=new Uint8Array(N),vis=new Uint8Array(N),rt={tricuspid:0,pulmonary:0,mitral:0,aortic:0,qv:0,qav:0,qej:0};
    let seed=12345;const rnd=()=>{seed=(seed*1664525+1013904223)>>>0;return seed/4294967296};
