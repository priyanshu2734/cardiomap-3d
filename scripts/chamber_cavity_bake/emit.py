import os
HERE=os.path.dirname(os.path.abspath(__file__))
import json
D=json.load(open('defs.json'))
def f(w): return '[%.4f,%.4f,%.4f,%.4f]'%tuple(w)
def chain(ws): return '['+','.join(f(w) for w in ws)+']'
r=D['right'][0];s=r['segEnd']
out=['/* BAKED:START (generated by the cavity bake; do not edit by hand) */',
 'const CAVITY={',
 ' /* waypoints [x,y,z,r] in mesh metres inside the enclosed cavities (outside the wall solids), r = lateral radius allowed (<= 70% of the clearance to the nearest wall) */',
 ' right:{atrium:%s,ventricle:%s},'%(chain(r['wp'][s[0]+1:s[1]+1]),chain(r['wp'][s[1]+1:s[2]+1])),
 ' left:{veins:{']
names=['lpv_up','lpv_low','rpv_up','rpv_low'];vents=[]
parts=[]
for n,p in zip(names,D['left']):
    e=p['segEnd'];parts.append('  %s:%s'%(n,chain(p['wp'][e[0]+1:e[1]+1])));vents.append(chain(p['wp'][e[1]+1:e[2]+1]))
assert len(set(vents))==1
out.append(',\n'.join(parts));out.append(' },ventricle:%s}'%vents[0]);out.append('};');out.append('/* BAKED:END */')
open('baked.js','w').write('\n'.join(out)+'\n');print(len('\n'.join(out)),'bytes')
