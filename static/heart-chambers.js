  const VESSEL_R=0.6;           /* particle lateral radius inside a vessel stub = tube radius x 0.6 */
  const DROP_NEAR=0.004;        /* outlet vessel's first point is dropped when it lies within 4 mm of the valve centre */
  const RIGHT_IN=['svc'],LEFT_IN=['lpv_up','lpv_low','rpv_up','rpv_low'];
  function vesselPts(g,reverse){const r=g.radius*VESSEL_R,a=g.points.map(p=>[p[0],p[1],p[2],r]);return reverse?a.reverse():a}
